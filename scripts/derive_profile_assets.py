#!/usr/bin/env python3
"""Derive a target profile's extraction map from exact shared payload bytes."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

from rom_profiles import ProfileError, load_profiles, select_profile


def fail(message: str) -> None:
    print(f"[ERROR] {message}", file=sys.stderr)
    raise SystemExit(1)


def parse_address(value: str) -> int:
    if not isinstance(value, str) or not value.lower().startswith("0x"):
        raise ValueError(f"invalid address: {value!r}")
    return int(value, 16)


def all_occurrences(image: bytes, payload: bytes, limit: int = 2) -> list[int]:
    """Return enough exact occurrences to distinguish unique from ambiguous."""
    found: list[int] = []
    cursor = image.find(payload)
    while cursor >= 0 and len(found) < limit:
        found.append(cursor)
        cursor = image.find(payload, cursor + 1)
    return found


def load_overrides(path: Path, base_profile: str, target_profile: str) -> dict[str, dict[str, Any]]:
    document = json.loads(path.read_text(encoding="utf-8"))
    if document.get("schema_version") != 1:
        raise ValueError("unsupported asset-override schema")
    if document.get("base_profile") != base_profile:
        raise ValueError("asset overrides name the wrong base profile")
    if document.get("target_profile") != target_profile:
        raise ValueError("asset overrides name the wrong target profile")
    result: dict[str, dict[str, Any]] = {}
    for record in document.get("overrides", []):
        name = record.get("name")
        if not isinstance(name, str) or not name:
            raise ValueError("asset override has no name")
        if name in result:
            raise ValueError(f"duplicate asset override: {name}")
        if not isinstance(record.get("reason"), str) or not record["reason"]:
            raise ValueError(f"asset override has no reason: {name}")
        result[name] = record
    return result


def reference_matches(image: bytes, reference: dict[str, Any]) -> bool:
    return (
        len(image) == reference["size"]
        and hashlib.sha1(image).hexdigest() == reference["sha1"]
        and hashlib.sha256(image).hexdigest() == reference["sha256"]
    )


def derive_assets(
    base_manifest: dict[str, Any],
    base_image: bytes,
    target_image: bytes,
    overrides: dict[str, dict[str, Any]],
    shared_start: int,
) -> list[dict[str, Any]]:
    derived: list[dict[str, Any]] = []
    used_overrides: set[str] = set()
    for base in base_manifest["assets"]:
        name = base["name"]
        base_start = parse_address(base["address"])
        base_end = parse_address(base["end"])
        payload = base_image[base_start:base_end]
        override = overrides.get(name)
        if override is not None:
            start = parse_address(override["address"])
            end = parse_address(override["end"])
            used_overrides.add(name)
        elif base_start >= shared_start:
            start, end = base_start, base_end
            if target_image[start:end] != payload:
                raise ValueError(f"{name}: declared shared-tail bytes differ")
        else:
            occurrences = all_occurrences(target_image, payload)
            if len(occurrences) != 1:
                description = "not found" if not occurrences else "ambiguous"
                raise ValueError(f"{name}: exact target payload is {description}; add an override")
            start = occurrences[0]
            end = start + len(payload)
        if end <= start or end > len(target_image):
            raise ValueError(f"{name}: target range is invalid")
        data = target_image[start:end]
        path = override.get("path", base["path"]) if override else base["path"]
        region = override.get("region", base["region"]) if override else base["region"]
        derived.append(
            {
                "name": name,
                "path": path,
                "region": region,
                "address": f"0x{start:X}",
                "end": f"0x{end:X}",
                "size": len(data),
                "sha1": hashlib.sha1(data).hexdigest(),
            }
        )
    unused = set(overrides) - used_overrides
    if unused:
        raise ValueError("unused asset overrides: " + ", ".join(sorted(unused)))
    paths = [asset["path"] for asset in derived]
    if len(paths) != len(set(paths)):
        raise ValueError("derived asset map contains duplicate paths")
    return derived


def range_text(assets: list[dict[str, Any]], base_profile: str, target_profile: str) -> str:
    lines = [
        f"# Alien Soldier {target_profile.upper()} ROM binary data segments",
        "# Generated by scripts/derive_profile_assets.py",
        f"# Exact payload mapping from profile {base_profile} to {target_profile}",
        "# Format: name,start,end,subdir",
        "",
    ]
    for asset in assets:
        lines.append(f"{asset['name']},{asset['address']},{asset['end']},{asset['region']}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profiles", default="config/rom_profiles.json")
    parser.add_argument("--base-profile", default="jp")
    parser.add_argument("--target-profile", default="eu")
    parser.add_argument("--base-manifest", default="assets/manifest.json")
    parser.add_argument("--overrides", default="config/eu_asset_overrides.json")
    args = parser.parse_args()
    try:
        profile_path = Path(args.profiles)
        profiles = load_profiles(profile_path)
        base = select_profile(profile_path, args.base_profile)
        target = select_profile(profile_path, args.target_profile)
        base_image = Path(base["reference_rom"]["filename"]).read_bytes()
        target_image = Path(target["reference_rom"]["filename"]).read_bytes()
        if not reference_matches(base_image, base["reference_rom"]):
            raise ValueError("base ROM does not match its declared profile")
        if not reference_matches(target_image, target["reference_rom"]):
            raise ValueError("target ROM does not match its declared profile")
        base_manifest = json.loads(Path(args.base_manifest).read_text(encoding="utf-8"))
        overrides = load_overrides(Path(args.overrides), args.base_profile, args.target_profile)
        shared_start = parse_address(profiles["shared_image_region"]["start"])
        assets = derive_assets(base_manifest, base_image, target_image, overrides, shared_start)
        target_manifest = {
            "schema_version": 1,
            "reference_rom": {
                **target["reference_rom"],
                "profile": args.target_profile,
                "platform": "Sega Mega Drive",
            },
            "derived_from": {
                "profile": args.base_profile,
                "manifest": args.base_manifest,
                "overrides": args.overrides,
            },
            "assets": assets,
        }
        manifest_path = Path(target["asset_manifest"])
        ranges_path = Path(target["asset_ranges"])
        manifest_path.write_text(
            json.dumps(target_manifest, indent=2) + "\n",
            encoding="utf-8",
            newline="",
        )
        ranges_path.write_text(
            range_text(assets, args.base_profile, args.target_profile),
            encoding="utf-8",
            newline="",
        )
        print(f"[OK] Derived {len(assets)} assets for profile {args.target_profile}")
        print(f"[OK] Wrote {manifest_path} and {ranges_path}")
        return 0
    except (OSError, UnicodeError, json.JSONDecodeError, ProfileError, ValueError) as error:
        fail(str(error))
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
